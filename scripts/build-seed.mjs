const categories = src.map(([name, note, items], ci) => ({
  id: `c${ci + 1}`,
  name,
  note,
  hidden: false,
  items: items.map(([iname, desc, price, unit = '']) => ({
    id: `i${++n}`,
    name: iname,
    desc,
    price: price.replace('?', ''),
    unit,
    hidden: false,
    check: price.endsWith('?'),
  })),
}));

